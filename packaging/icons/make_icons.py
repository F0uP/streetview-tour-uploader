"""
Draw the app icon and write it in every format the builds need.

The logo is a 360° ring, open where you stand (the gold dot), on a violet tile.
This script is the single source of its geometry: it writes icon.svg, renders
it with headless Chrome (Playwright) at each size, and packs the results:

  icon.svg              scalable source (Linux hicolor/scalable, README)
  png/<size>.png        16 … 1024 px (Linux hicolor icons)
  app.ico               Windows (exe, installer, tray)
  app.icns              macOS (.app bundle)
  ../../editor/favicon.png, ../../editor/logo.svg

Only needed when the logo changes; the outputs are committed.

  pip install playwright pillow && playwright install chromium
  python packaging/icons/make_icons.py
"""

import base64
import math
import shutil
from pathlib import Path

from PIL import Image
from playwright.sync_api import sync_playwright

HERE = Path(__file__).parent.resolve()
ROOT = HERE.parent.parent

VIOLET = ('#a98bff', '#7c4dff', '#5426d0')
GOLD = '#f6b93b'
CENTER, RADIUS, STROKE = 512, 236, 78
GAP_AT, HALF_GAP = -45, 31        # degrees; 0 = east, clockwise
DOT_RADIUS = 60
SIZES = [16, 24, 32, 48, 64, 128, 256, 512, 1024]


def point(angle, r=RADIUS):
    a = math.radians(angle)
    return CENTER + r * math.cos(a), CENTER + r * math.sin(a)


def svg(margin=80):
    """margin: space around the tile; small icons use less so they don't look tiny."""
    x0, y0 = point(GAP_AT + HALF_GAP)
    x1, y1 = point(GAP_AT - HALF_GAP + 360)
    dx, dy = point(GAP_AT)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">
  <!-- Streetview Tour Editor: a 360° ring, open where you stand (the gold dot).
       Generated by make_icons.py - change it there. -->
  <defs>
    <linearGradient id="tile" x1="0.15" y1="0" x2="0.85" y2="1">
      <stop offset="0" stop-color="{VIOLET[0]}"/>
      <stop offset="0.55" stop-color="{VIOLET[1]}"/>
      <stop offset="1" stop-color="{VIOLET[2]}"/>
    </linearGradient>
  </defs>
  <rect x="{margin}" y="{margin}" width="{1024 - 2 * margin}" height="{1024 - 2 * margin}" rx="{round(196 * (1024 - 2 * margin) / 864)}" fill="url(#tile)"/>
  <path d="M{x0:.1f} {y0:.1f} A{RADIUS} {RADIUS} 0 1 1 {x1:.1f} {y1:.1f}" fill="none" stroke="#fff" stroke-width="{STROKE}" stroke-linecap="round"/>
  <circle cx="{dx:.1f}" cy="{dy:.1f}" r="{DOT_RADIUS}" fill="{GOLD}"/>
</svg>
'''


def main():
    source = svg()
    (HERE / 'icon.svg').write_text(source, encoding='utf-8')
    png_dir = HERE / 'png'
    png_dir.mkdir(exist_ok=True)

    # Render every size straight from the vector, so small icons stay crisp.
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page()
        for size in SIZES:
            vector = svg(margin=24) if size <= 48 else source
            page.set_viewport_size({'width': size, 'height': size})
            page.set_content(f'<html><body style="margin:0;background:transparent">'
                             f'<img src="data:image/svg+xml;base64,{base64.b64encode(vector.encode()).decode()}" '
                             f'width="{size}" height="{size}" style="display:block"></body></html>')
            page.wait_for_timeout(50)
            page.screenshot(path=str(png_dir / f'{size}.png'), omit_background=True)
        browser.close()

    images = {size: Image.open(png_dir / f'{size}.png').convert('RGBA') for size in SIZES}
    ico_sizes = [16, 24, 32, 48, 64, 128, 256]
    images[256].save(HERE / 'app.ico', sizes=[(s, s) for s in ico_sizes],
                     append_images=[images[s] for s in ico_sizes if s != 256])
    images[1024].save(HERE / 'app.icns')
    shutil.copy(png_dir / '64.png', ROOT / 'editor' / 'favicon.png')
    (ROOT / 'editor' / 'logo.svg').write_text(svg(margin=0), encoding='utf-8')  # sidebar of the editor
    print('Wrote', ', '.join(sorted(p.name for p in HERE.iterdir() if p.is_file())), 'and png/')


if __name__ == '__main__':
    main()
